async function ensureProjectSetupDirectory(directory, label) {
  try {
    await fsp.mkdir(directory, { mode: 0o700 });
  } catch (err) {
    if (err.code !== 'EEXIST') throw err;
  }
  const stat = await fsp.lstat(directory);
  if (!stat.isDirectory() || stat.isSymbolicLink()) {
    throw new Error(`${label} must be a real directory`);
  }
}

async function durableProjectWrite(target, content, temporaryPrefix) {
  const directory = path.dirname(target);
  const temporary = path.join(
    directory,
    `.${temporaryPrefix}.tmp-${process.pid}-${crypto.randomBytes(8).toString('hex')}`
  );
  let handle;
  let renamed = false;
  try {
    handle = await fsp.open(
      temporary,
      fs.constants.O_CREAT | fs.constants.O_EXCL | fs.constants.O_WRONLY,
      0o600
    );
    await handle.writeFile(content, 'utf8');
    await handle.sync();
    await handle.close();
    handle = null;
    await fsp.rename(temporary, target);
    renamed = true;
    try {
      const directoryHandle = await fsp.open(directory, fs.constants.O_RDONLY);
      try { await directoryHandle.sync(); } finally { await directoryHandle.close(); }
    } catch (err) {
      const unsupported = ['EINVAL', 'ENOTSUP', 'EISDIR'].includes(err.code)
        || (process.platform === 'win32' && ['EPERM', 'EACCES'].includes(err.code));
      if (!unsupported) throw err;
    }
  } catch (err) {
    if (handle) await handle.close().catch(() => {});
    if (!renamed) await fsp.unlink(temporary).catch(() => {});
    err.projectWriteCommitted = renamed;
    throw err;
  }
}


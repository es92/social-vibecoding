async function codexSetup(args, io, launcherPath) {
  const { options, positional } = parseOptions(
    args,
    new Set(['--profile', '--forward-env-token'])
  );
  if (positional.length) throw new Error('codex setup accepts no positional arguments');
  const rootCandidate = path.resolve(__dirname, '../..');
  const checkoutRoot = await fsp.realpath(rootCandidate);
  const realLauncher = await fsp.realpath(launcherPath);
  if (realLauncher !== path.join(checkoutRoot, 'tools', 'social-vibecoding')) {
    throw new Error('Launcher resolves outside this checkout');
  }
  const nodePath = await fsp.realpath(process.execPath);
  const codexDirectory = path.join(checkoutRoot, '.codex');
  const hookPath = path.join(codexDirectory, 'hooks', 'promotion-approval.js');
  const target = path.join(codexDirectory, 'config.toml');
  const lockPath = path.join(codexDirectory, 'config.toml.lock');
  const directoryStat = await fsp.lstat(codexDirectory);
  if (!directoryStat.isDirectory() || directoryStat.isSymbolicLink()) {
    throw new Error('.codex must be a real directory');
  }
  const hookStat = await fsp.lstat(hookPath);
  if (!hookStat.isFile() || hookStat.isSymbolicLink()
      || await fsp.realpath(hookPath) !== hookPath) {
    throw new Error('Promotion approval hook must be a real file in this checkout');
  }
  const hookSha256 = crypto.createHash('sha256')
    .update(await fsp.readFile(hookPath))
    .digest('hex');
  const tracked = spawnSync('git', ['ls-files', '--error-unmatch', '.codex/config.toml'], {
    cwd: checkoutRoot,
    stdio: 'ignore',
    shell: false,
  });
  if (tracked.error || ![0, 1].includes(tracked.status)) {
    throw new Error('Could not verify whether .codex/config.toml is Git-tracked');
  }
  if (tracked.status === 0) throw new Error('Refusing to overwrite a Git-tracked .codex/config.toml');

  const lock = await state.acquireLock(lockPath, {
    timeoutMs: 5000,
    recoverAfterMs: 30000,
    operation: 'codex_setup',
    secureDirectory: false,
  });
  try {
    let existingProfile = null;
    let existing = null;
    try {
      const stat = await fsp.lstat(target);
      if (stat.isSymbolicLink() || !stat.isFile()) {
        throw new Error('Unsafe .codex/config.toml');
      }
      existing = await fsp.readFile(target, 'utf8');
      if (!existing.startsWith(`${GENERATED_HEADER}\n`)) {
        io.err(setupToml({
          nodePath,
          scriptPath: realLauncher,
          checkoutRoot,
          profile: options.profile || 'production',
          forwardEnv: !!options.forward_env_token,
          hookSha256,
        }));
        throw new Error('Existing .codex/config.toml is not generated; merge the table printed above manually');
      }
      const match = existing.match(/\n  "--profile",\n  "([^"]+)",/);
      if (match) existingProfile = match[1];
    } catch (err) {
      if (err.code !== 'ENOENT') throw err;
    }
    const profile = await state.selectedProfile(
      options.profile || existingProfile || 'production'
    );
    const document = setupToml({
      nodePath,
      scriptPath: realLauncher,
      checkoutRoot,
      profile: profile.name,
      forwardEnv: !!options.forward_env_token,
      hookSha256,
    });
    if (existing !== document) {
      const temp = path.join(codexDirectory, `.config.toml.tmp-${process.pid}-${crypto.randomBytes(8).toString('hex')}`);
      const handle = await fsp.open(temp, fs.constants.O_CREAT | fs.constants.O_EXCL | fs.constants.O_WRONLY, 0o600);
      try {
        await handle.writeFile(document, 'utf8');
        await handle.sync();
      } finally {
        await handle.close();
      }
      await fsp.rename(temp, target);
      try {
        const directoryHandle = await fsp.open(codexDirectory, fs.constants.O_RDONLY);
        try { await directoryHandle.sync(); } finally { await directoryHandle.close(); }
      } catch (err) {
        const unsupported = ['EINVAL', 'ENOTSUP', 'EISDIR'].includes(err.code)
          || (process.platform === 'win32' && ['EPERM', 'EACCES'].includes(err.code));
        if (!unsupported) throw err;
      }
      io.out(`Wrote ${target}\n`);
    } else {
      io.out(`${target} is already up to date.\n`);
    }
  } finally {
    await lock.release();
  }
  io.out('Restart or reload Codex to apply this configuration. After the first prompt, Codex will ask you to use /hooks if the generated promotion guard is not active. Authenticate only from a trusted, reviewed checkout.\n');
  return 0;
}


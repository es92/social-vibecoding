function validateClaudeSetupMarker(value) {
  if (!isExactObject(value, [
    'generated_by',
    'version',
    'checkout_root',
    'profile',
    'server',
  ])
      || value.generated_by !== CLAUDE_MARKER_GENERATOR
      || value.version !== 1
      || typeof value.checkout_root !== 'string'
      || !path.isAbsolute(value.checkout_root)
      || !state.PROFILE_RE.test(value.profile)
      || !isExactObject(value.server, ['type', 'command', 'args'])
      || value.server.type !== 'stdio'
      || typeof value.server.command !== 'string'
      || !path.isAbsolute(value.server.command)
      || !Array.isArray(value.server.args)
      || value.server.args.length !== 4
      || typeof value.server.args[0] !== 'string'
      || !path.isAbsolute(value.server.args[0])
      || value.server.args[0] !== path.join(
        value.checkout_root,
        'tools',
        'social-vibecoding'
      )
      || value.server.args[1] !== 'mcp'
      || value.server.args[2] !== '--profile'
      || value.server.args[3] !== value.profile) {
    throw new Error('Existing Claude setup marker is not generated; remove it only after reviewing the configured local MCP server');
  }
  return value;
}

